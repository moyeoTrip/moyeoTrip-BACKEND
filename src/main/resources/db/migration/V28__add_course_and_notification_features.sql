CREATE TABLE travel_course_ratings (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    travel_course_id NUMBER(19) NOT NULL,
    chat_room_id NUMBER(19) NOT NULL,
    user_id NUMBER(19) NOT NULL,
    score NUMBER(1) NOT NULL,
    created_datetime TIMESTAMP NOT NULL,
    updated_datetime TIMESTAMP NOT NULL,
    CONSTRAINT fk_course_rating_course FOREIGN KEY (travel_course_id) REFERENCES travel_courses(id) ON DELETE CASCADE,
    CONSTRAINT fk_course_rating_room FOREIGN KEY (chat_room_id) REFERENCES chat_rooms(id) ON DELETE CASCADE,
    CONSTRAINT fk_course_rating_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT uk_course_rating_room_user UNIQUE (chat_room_id, user_id),
    CONSTRAINT ck_course_rating_score CHECK (score BETWEEN 1 AND 5)
);

CREATE INDEX ix_course_rating_course ON travel_course_ratings(travel_course_id);

