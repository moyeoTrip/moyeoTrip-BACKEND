    (duration_minutes IS NOT NULL AND trip_nights IS NULL AND trip_days IS NULL) OR
    (duration_minutes IS NULL AND trip_nights IS NOT NULL AND trip_days IS NOT NULL) OR
    (duration_minutes IS NULL AND trip_nights IS NULL AND trip_days IS NULL)
);

